#include <Cartographic/ellipsoid.hpp>
//==============================================================================
namespace Cartographic
{
namespace Ellipsoid
{
//==============================================================================
Unknown::Unknown(Meters a, Units f)
: a_(a),
  e2_((2. - f) * f)
{}
//==============================================================================
Meters Unknown::A() const
{
  return a_;
}
//==============================================================================
Units Unknown::E2() const
{
  return e2_;
}
//==============================================================================
} // !Ellipsoid
//==============================================================================
Sphere::Sphere(Meters r)
: r_(r)
{}
//==============================================================================
Meters Sphere::A() const
{
  return r_;
}
//==============================================================================
Units Sphere::E2() const
{
  return 0.;
}
//==============================================================================
} // !Cartographic


