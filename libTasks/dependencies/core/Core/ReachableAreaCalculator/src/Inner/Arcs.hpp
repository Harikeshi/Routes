/*!
 * \brief Полидуга
 * \details Набор сопряжённых или пересеченных дуг.
 */
class Polyarc
{
//==============================================================================
public:
//==============================================================================
  /*!
   * \brief Конструктор
   */
  Polyarc() noexcept
    : mBox(Point2D(), Point2D())
  { }
//==============================================================================
  /*!
   * \brief Конструктор
   * \param[in] arc - дуга.
   */
  Polyarc(const Arc& arc) noexcept;
//==============================================================================
  /*!
   * \brief Конструктор
   * \param[in] arcs - дуги.
   */
  Polyarc(const std::deque<Arc>& arcs) noexcept;
//==============================================================================
  /*!
   * \brief beginArc -- метод, возвращающий начальную дугу полидуги.
   * \return начальная дуга полидуги.
   * \throws ReachableAreaFailure # ArcsArcReferenceFromEmptyPolyarc
   */
  const Arc& beginArc() const;
//==============================================================================
  /*!
   * \brief endArc -- метод, возвращающий конечную дугу полидуги.
   * \return конечная дуга полидуги.
   * \throws ReachableAreaFailure # ArcsArcReferenceFromEmptyPolyarc
  */
  const Arc& endArc() const;
//==============================================================================
  /*!
   * \brief addToBegin -- метод, добавляющий дугу в начало полидуги.
   * \param[in] arc -- дуга, которую требуется добавить.
   * \return true, если дуга была успешно добавлена;
   *         false -- иначе.
   */
  bool addToBegin(const Arc& arc) noexcept;
//==============================================================================
  /*!
   * \brief addToEnd -- метод, добавляющий дугу в конец полидуги.
   * \param[in] arc -- дуга, которую требуется добавить.
   * \return true, если дуга была успешно добавлена;
   *         false -- иначе.
   */
  bool addToEnd(const Arc& arc) noexcept;
//==============================================================================
  /*!
   * \brief addToEndWithoutCheck -- метод,
   * добавляющий дуги другой полидуги в конец полидуги.
   * \param[in] polyarc -- полидуга, дуги которой требуется добавить.
   */
  void addToEndWithoutCheck(const Polyarc& polyarc) noexcept;
//==============================================================================
  /*!
   * \brief arcs -- метод, возвращающий дуги полидуги.
   * \return -- ссылка на двустороннюю очередь дуг.
   */
  inline const std::deque<Arc>& arcs() const noexcept
  {
    return mArcs;
  }
//==============================================================================
  /*!
   * \brief line -- метод, возвращающий приближение полидуги
   * в виде ломаной линии.
   * \param[in|out] resultPolyarc  - массив вершин,
   * в который будут дозаписаны вершины полигонального приближения полидуги;
   * \param[in]  segmentsNumber - количество точек для представления окружности.
   * \details Кольцо,
   * сформированное этим методом,
   * имеет направление обхода "против часовой стрелки".
   */
  void line(
    std::vector<Point2D>& resultPolyarc,
    uinttype segmentsNumber) const noexcept;
//==============================================================================
  /*!
   * \brief get -- метод, возвращающий дугу по её id и углу,
   * который она содержит.
   * \param[in]     arcId    - id дуги, которую хотим получить;
   * \param[in]     angle    - угол, принадлежащий дуге;
   * \param[in|out] position - позиция дуги в списке дуг;
   * \param[in|out] arc      - дуга;
   * \return true, если дуга с заданными праметрми найдена в настоящей полидуге;
   *         false - иначе.
   * \details Если дуга с заданными параметрами не нашлась,
   * объекты, ссылки на которые передаются в качестве возвращаемых параметров,
   * остаются нетронутыми, как и сами эти объекты.
   */
  bool getArc(
    uinttype arcId,
    Angle angle,
    uinttype& position,
    Arc& arc) const noexcept;
//==============================================================================
  /*!
   * \brief isClosed -- метод, проверяющий замкнутость полидуги.
   * \return true, если полидуга замкнута;
   *         false - иначе.
   */
  bool isClosed() const noexcept;
//==============================================================================
  /*!
   * \brief box -- метод, возвращающий коробку.
   * \return коробка.
   */
  inline const Box2D& box() const noexcept
  {
    return mBox;
  }
//==============================================================================
  /*!
   * \brief toPolygon -- метод,
   * возвращающий полигональное представление полидуги.
   *
   * \param[in] segmentsNumber -- количество точек,
   * которое требуется использовать для приближения целой окружности.
   *
   * \return искомый многоугольник.
   */
  Polygon2D toPolygon(uinttype segmentsNumber = 360U) const noexcept;
//==============================================================================
protected:
//==============================================================================
  std::deque<Arc> mArcs; //!< Составляющие дуги.
  Box2D           mBox;  //!< Коробка.
//==============================================================================
};
