/*!
 * \brief Геометрия, состоящая из набора полидуг и полилиний.
 */
class SemiarcContour
{
//==============================================================================
public:
//==============================================================================
  /*!
   * \brief Конструктор.
   */
  inline SemiarcContour() noexcept
  { }
//==============================================================================
  /*!
   * \brief push -- метод, добавляющий полидугу в конец геометрии.
   * \param[in] polyarc - полидуга, которую требуется добавить.
   */
  void push(const Polyarc& polyarc) noexcept;
//==============================================================================
  /*!
   * \brief push -- метод, добавляющий очередную вершину в конец геометрии.
   * \param[in] point - вершина, которую требуется добавить.
   */
  void push(const Point2D& point) noexcept;
//==============================================================================
  /*!
   * \brief push -- метод, добавляющий ломаную в конец геометрии.
   * \param[in] polyline - ломаная, которую требуется добавить.
   */
  void push(const std::vector<Point2D>& polyline) noexcept;
//==============================================================================
  /*!
   * \brief line -- метод, возвращающий представление настоящей геометрии
   * в виде ломаной линии.
   * \param[in|out] resultSemiarc -- ломаная линия,
   * в конец которой будет записано приближение геометрии;
   * \param[in] segmentsNumber -- количество точек,
   * которое требуется использовать для приближения целой окружности.
   * \details Кольцо,
   * сформированное этим методом,
   * имеет направление обхода "против часовой стрелки".
   */
  void line(
    std::vector<Point2D>& resultSemiarc,
    uinttype segmentsNumber) const noexcept;
//==============================================================================
  /*!
   * \brief toPolygon -- метод,
   * возвращающий полигональное представление геометрии.
   *
   * \param[in] segmentsNumber -- количество точек,
   * которое требуется использовать для приближения целой окружности.
   *
   * \details геометрия интерпретируется
   * как внешнее кольцо получаемого многоугольника.
   *
   * \return искомый многоугольник.
   */
  Polygon2D toPolygon(uinttype segmentsNumber = 360U) const noexcept;
//==============================================================================
protected:
//==============================================================================
  std::vector<Polyarc> mPolyarcs;  //!< Полидуги.
  std::vector<Point2D> mPoints;    //!< Точки.
  //!< Типы элементов (считая от начала, true - точка, false - полидуга).
  std::vector<bool>    mElemTypes; 
//==============================================================================
};
