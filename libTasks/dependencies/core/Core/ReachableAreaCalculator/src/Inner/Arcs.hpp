typedef unsigned int uinttype; //! целочисленный беззнаковый тип
//==============================================================================
/*!
 * \brief Тип границы (обрыва) дуги.
 */
enum ArcBeginEndInfo
{
  ByRefPoint = 0, //! из-за точки преломления;
  ByViewZone = 1, //! из-за ограничения зоны обзора;
  ByEdge = 2,     //! из-за границы;
  ByCut = 3       //! из-за обрезки склейщиком.
};
//==============================================================================
//==============================================================================
/*!
 * \brief Дуга.
 */
class Arc
{
//==============================================================================
public:
//==============================================================================
  /*!
   * \brief Конструктор.
   */
  Arc() noexcept
    : mBox(Point2D(), Point2D())
  { }
//==============================================================================
  /*!
   * \brief Конструктор.
   * \param[in] center     - центральная точка;
   * \param[in] centerId   - глобальный идентификатор центральной точки;
   * \param[in] radius     - радиус дуги;
   * \param[in] beginAngle - начальный угол;
   * \param[in] endAngle   - конечный угол.
   * \param[in] isEmpty    - параметр, говорящий о том, как интерперетировать
   *                       совпадение начального и конечного углов:
   *                       true -- размер дуги равен нулю (пустая дуга),
   *                       false -- размер дуги равен 2π (полная дуга).
   */
  Arc(
    const Point2D& center,
    uinttype centerId,
    double radius,
    const Angle& beginAngle,
    const Angle& endAngle,
    bool isEmpty = true) noexcept;
//==============================================================================
  /*!
   * \brief setId -- метод, устанавливающий новый идентификатор дуги.
   * \param[in] id -- новый идентификатор дуги.
   */
  inline void setId(const uinttype id) noexcept
  {
    mId = id;
  }
//==============================================================================
  /*!
   * \brief setBeginInfo -- метод, устанавливающий тип обрыва начала для дуги.
   * \param[in] info -- тип обрыва начала дуги.
   * \param[in] id -- уникальный идентификатор
   * начальной вершины ребра полигона окружения, которым обрывается начало дуги
   * (если оно обрывается ребром).
   */
  inline void setBeginInfo(ArcBeginEndInfo info, uinttype id = 0) noexcept
  {
    mBeginInfo = info;
    mArcBeginInfo = id;
  }
//==============================================================================
  /*!
   * \brief setEndInfo -- метод, устанавливающий тип обрыва конца для дуги.
   * \param[in] info -- тип обрыва конца дуги.
   * \param[in] id -- уникальный идентификатор
   * начальной вершины ребра полигона окружения, которым обрывается конец дуги
   * (если он обрывается ребром).
   */
  inline void setEndInfo(ArcBeginEndInfo info, uinttype id = 0) noexcept
  {
    mEndInfo = info;
    mArcEndInfo = id;
  }
//==============================================================================
  /*!
   * \brief setBeginAngle -- метод, устанавливающий начальный угол дуги.
   * \param[in] angle -- значение угла, которое требуется установить.
   * \param[in] isEmpty -- параметр, говорящий о том, как интерперетировать
   *                       совпадение начального и конечного углов:
   *                       true -- размер дуги равен нулю (пустая дуга),
   *                       false -- размер дуги равен 2π (полная дуга).
   */
  void setBeginAngle(Angle angle, bool isEmpty = true) noexcept;
//==============================================================================
  /*!
   * \brief setEndAngle -- метод, устанавливающий конечный угол дуги.
   * \param[in] angle -- значение угла, которое требуется установить.
   * \param[in] isEmpty -- параметр, говорящий о том, как интерперетировать
   *                       совпадение начального и конечного углов:
   *                       true -- размер дуги равен нулю (пустая дуга),
   *                       false -- размер дуги равен 2π (полная дуга).
   */
  void setEndAngle(Angle angle, bool isEmpty = true) noexcept;
//==============================================================================
  /*!
   * \brief setBeginEndAngles -- метод,
   * устанавливающий начальный и конечный углы дуги.
   * \param[in] beginAngle -- значение,
   * которое требуется установить в качестве начального угла.
   * \param[in] endAngle -- значение,
   * которое требуется установить в качестве конечного угла.
   * \param[in] isEmpty -- параметр, говорящий о том, как интерперетировать
   *                       совпадение начального и конечного углов:
   *                       true -- размер дуги равен нулю (пустая дуга),
   *                       false -- размер дуги равен 2π (полная дуга).
   * \details Задаётся начальный угол и пересчитывается размер дуги.
   */
  void
  setBeginEndAngles(
    Angle beginAngle,
    Angle endAngle,
    bool isEmpty = true) noexcept;
//==============================================================================
  /*!
   * \brief setTaskInfo -- метод, устанавливающий id заданий, создавшего дугу и 
   *      породившего задание, которое создало дугу.
   * \param[in] taskId -- id задания, создавшего дугу.
   * \param[in] parentTaskId -- id задания, породившего задание, создавшее дугу.
   */
  inline void setTaskInfo(uinttype taskId, uinttype parentTaskId) noexcept
  {
    mTaskId = taskId;
    mParentTaskId = parentTaskId;
  }
//==============================================================================
  /*!
   * \brief id -- метод, возвращающий идентификатор дуги.
   * \return идентификатор дуги.
   */
  inline uinttype id() const noexcept
  {
    return mId;
  }
//==============================================================================
  /*!
   * \brief center -- метод, возвращающий центральную точку дуги.
   * \return ссылка на центральную точку дуги.
   */
  inline const Point2D& center() const noexcept
  {
    return mCenter;
  }
//==============================================================================
  /*!
   * \brief centerId -- метод,
   * возвращающий идентификатор центральной точки дуги.
   * \return идентификатор центральной точки дуги.
   */
  inline uinttype centerId() const noexcept
  {
    return mCenterId;
  }
//==============================================================================
  /*!
   * \brief taskId -- метод, возвращающй id задания, создавшего дугу.
   * \return id задания, создавшего дугу.
   */
  inline uinttype taskId() const noexcept
  {
    return mTaskId;
  }
//==============================================================================
  /*!
   * \brief parentTaskId -- метод, возвращающий id задания, породившего задание, 
   * которое создало дугу.
   * \return id задания, породившего задание, которое создало дугу.
   */
  inline uinttype parentTaskId() const noexcept
  {
    return mParentTaskId;
  }
//==============================================================================
  /*!
   * \brief radius -- метод, возвращающий радиус дуги.
   * \return радиус дуги.
   */
  inline double radius() const noexcept
  {
    return mRadius;
  }
//==============================================================================
  /*!
   * \brief beginAngle -- метод, возвращающий начальный угол дуги.
   * \return начальный угол дуги.
   */
  inline Angle beginAngle() const noexcept
  {
    return mBeginAngle;
  }
//==============================================================================
  /*!
   * \brief endAngle -- метод, возвращающий конечный угол дуги.
   * \return конечный угол дуги.
   */
  inline Angle endAngle() const noexcept
  {
    return Angle(mBeginAngle.value() + mSize);
  }
//==============================================================================
  /*!
   * \brief size -- метод, возвращающий размер дуги (в радианах).
   * \return размер дуги (в радианах).
   */
  inline double size() const noexcept
  {
    return mSize;
  }
//==============================================================================
  /*!
   * \brief beginInfo -- метод, возвращающий тип обрыва начала дуги.
   * \return тип обрыва начала дуги.
   */
  inline ArcBeginEndInfo beginInfo() const noexcept
  {
    return mBeginInfo;
  }
//==============================================================================
  /*!
   * \brief endInfo -- метод, возвращающий тип обрыва конца дуги.
   * \return тип обрыва конца дуги.
   */
  inline ArcBeginEndInfo endInfo() const noexcept
  {
    return mEndInfo;
  }
//==============================================================================
  /*!
   * \brief arcBeginInfo -- метод,
   * возвращающий дополнительную информацию о начале дуги.
   * \return дополнительная информация о начале дуги.
   * \details Если начало дуги обрывается стороной полигона окружения,
   * дополнительной информацией является id начальной точки
   * этой стороны полигона.
   */
  inline uinttype arcBeginInfo() const noexcept
  {
    return mArcBeginInfo;
  }
//==============================================================================
  /*!
   * \brief arcEndInfo -- метод,
   * возвращающий дополнительную информацию о конце дуги.
   * \return дополнительная информация о конце дуги.
   * \details Если конец дуги обрывается стороной полигона окружения,
   * дополнительной информацией является id начальной точки
   * этой стороны полигона.
   */
  inline uinttype arcEndInfo() const noexcept
  {
    return mArcEndInfo;
  }
//==============================================================================
  /*!
   * \brief beginPoint -- метод, возвращающий начальную точку дуги.
   * \return начальная точка дуги.
   */
  Point2D beginPoint() const noexcept;
//==============================================================================
  /*!
   * \brief endPoint -- метод, возвращающий конечную точку дуги.
   * \return конечная точка дуги.
   */
  Point2D endPoint() const noexcept;
//==============================================================================
  /*!
   * \brief box -- получение коробки.
   * \return коробка
   */
  inline const Box2D& box() const noexcept
  {
    return mBox;
  }
//==============================================================================
  /*!
   * \brief isPointInSector -- метод, определяющий принадлежность точки сектору.
   * \param[in] point  -- точка;
   * \return true, если точка принадлежит сектору;
   *         false -- иначе.
   */
  bool isPointInSector(const Point2D& point) const noexcept;
//==============================================================================
  /*!
   * \brief line - представление дуги как ломаной линии
   * \param[in|out] resultArc   - массив точек на плоскости,
   * куда будет дозаписана дуга в виде набора вершин ломаной линии;
   * \param[in]  segmentsNumber - количество точек для представления
   * окружности.
   * \details Кольцо,
   * сформированное этим методом,
   * имеет направление обхода "против часовой стрелки".
   */
  void
  line(std::vector<Point2D>& resultArc, uinttype segmentsNumber) const noexcept;
//==============================================================================
protected:
//==============================================================================
  uinttype        mId = 0U;       //!< идентификатор дуги;
  Point2D         mCenter;        //!< центральная точка;
  uinttype        mCenterId = 0U; //!< идентификатор центральной точки;
  uinttype        mTaskId = 0U;   //!< id задания, создавшего дугу;
  uinttype        mParentTaskId;  //!< id задания, породившего задание,
                                  //!< которое создало дугу;
  double          mRadius = 0.;   //!< радиус дуги;
  Angle           mBeginAngle;    //!< начальный угол;
  double          mSize = 0.;     //!< размер дуги (радианы);
  ArcBeginEndInfo mBeginInfo;     //!< тип обрыва начала;
  ArcBeginEndInfo mEndInfo;       //!< тип обрыва конца;
  uinttype        mArcBeginInfo   //!< доп. информация начала
                  = 0U;           //!< (зависит от mBeginInfo).
                                  //!< ByRefPoint - id точки преломления;
                                  //!< ByViewZone - не используется;
                                  //!< ByEdge - id начальной точки границы;
                                  //!< ByCut - не используется;
  uinttype        mArcEndInfo     //!< доп. информация конца (зависит от
                  = 0U;           //!< mEndInfo, аналогично mArcBeginInfo);  
  Box2D           mBox;           //!< коробка;
//==============================================================================
  /*!
   * \brief recalcBox -- функция пересчёта коробки.
   */
  void recalcBox() noexcept;
//==============================================================================
};
